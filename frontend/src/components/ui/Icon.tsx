export function Icon({ name, size = 20, className, strokeWidth = 1.75 }: { name: IconName; size?: number; className?: string; strokeWidth?: number }) {
  const C = ICONS[name];
  return <C className={className ? `icon ${className}` : "icon"} size={size} strokeWidth={strokeWidth} aria-hidden="true" focusable="false" />;
}
